# 9.2.3 gives zeta = 0.2 for the series-elastic mode; D7's flexible joint is the
# same kind of object and takes the same ratio.
COMPLIANCE_DAMPING_RATIO = 0.2

# 9.2.7 asks for D7's stiffness to be "calibrated by the first bending mode
# frequency" and names no frequency, and 9.2.10's D7 row is empty. The reference
# taken here is the control loop's Nyquist frequency, CONTROL_FREQ / 2: a
# structural mode there is by construction one the 20 Hz policy cannot observe or
# compensate, which is the whole reason D7 is kept as the defect that breaks (A4)
# (14.5 E-5). `link_compliance` then scales the compliance away from it, so
# k = I_eff * LINK_FLEX_REFERENCE_OMEGA^2 / link_compliance.
LINK_FLEX_REFERENCE_OMEGA = math.pi * CONTROL_FREQ

# 9.2.4's template, verbatim. solimp's third entry is the low-impedance dead-zone
# width and is set per fragment to b/2, so only head and tail are constants here.
BACKLASH_SOLREF = (0.005, 1.0)
BACKLASH_SOLIMP_HEAD = (0.2, 0.95)
BACKLASH_SOLIMP_TAIL = (0.9, 6.0)

# See the module docstring: the rotor inertia lives on the driven joint.
SHADOW_ARMATURE = 0.0

SHADOW_SUFFIX = {
    "D4hi": "_lash",
    "D3a": "_sea",
    "D7": "_flex",
}


def backlash_engagement(
    data: Any,
    equality_ids: tuple[int, ...],
    half_ranges: tuple[float, ...],
) -> np.ndarray:
    """Read D4hi engagement from the live equality-constraint residuals.

    MuJoCo stores active constraints in ``efc_*`` arrays, whose row indices are
    rebuilt as contacts appear and disappear.  ``equality_ids`` are model ids,
    not row indices, so each one must be resolved through the pair
    ``(efc_type, efc_id)`` on every frame.  The backlash equality pins the
    shadow joint at zero with a low-impedance band of ``half_range``; reaching
    either edge is the re-engaged state used by :class:`D4Field`.

    There is deliberately no fallback to qpos or wrapper memory.  A missing or
    duplicate equality row means the physical read-out promised by 9.2.4 is not
    available on that frame, and treating it as engaged would silently erase
    the support of the compensation field.
    """
    if len(equality_ids) != len(half_ranges):
        raise ValueError(
            f"{len(equality_ids)} backlash equality ids but {len(half_ranges)} half ranges"
        )
    if any(width <= 0.0 or not math.isfinite(width) for width in half_ranges):
        raise ValueError(f"backlash half ranges must be finite and positive, got {half_ranges}")

    nefc = int(data.nefc)
    kinds = np.asarray(data.efc_type[:nefc], dtype=np.int64)
    ids = np.asarray(data.efc_id[:nefc], dtype=np.int64)
    residuals = np.asarray(data.efc_pos[:nefc], dtype=np.float64)
    equality_kind = int(mujoco.mjtConstraint.mjCNSTR_EQUALITY)
    engaged = np.empty(len(equality_ids), dtype=bool)

    for i, (equality_id, half_range) in enumerate(
        zip(equality_ids, half_ranges, strict=True)
    ):
        rows = np.flatnonzero((kinds == equality_kind) & (ids == equality_id))
        if rows.size != 1:
            raise RuntimeError(
                f"backlash equality {equality_id} has {rows.size} active efc rows; "
                "D4hi engagement requires exactly one equality residual per frame"
            )
        residual = float(residuals[int(rows[0])])
        if not math.isfinite(residual):
            raise RuntimeError(
                f"backlash equality {equality_id} has non-finite efc_pos {residual}"
            )
        engaged[i] = abs(residual) >= half_range
    return engaged


class ShadowKind(str, Enum):
    """Which of the three graph-changing defects a fragment belongs to."""

    BACKLASH = "backlash"          # D4hi: co-axial, ranged, soft equality
    SERIES_ELASTIC = "series_elastic"  # D3a: co-axial, sprung, unranged
    LINK_FLEX = "link_flex"        # D7: bending axis, sprung, unranged


@dataclass(frozen=True)
class ShadowJointSpec:
    """One extra hinge, plus the equality constraint that goes with it.

    `axis` is in the parent body's frame, like every MJCF joint axis.
    `half_range` is None for the unranged kinds. `stiffness`/`damping` are None
    while they still depend on a compiled inertia.
    """

    name: str
    parent_joint: str
    kind: ShadowKind
    axis: tuple[float, float, float]
    pos: tuple[float, float, float]
    half_range: float | None
    stiffness: float | None
    damping: float | None
    armature: float = SHADOW_ARMATURE
    stiffness_per_inertia: float | None = None   # D7: k = stiffness_per_inertia * I_eff

    @property
    def is_resolved(self) -> bool:
        if self.kind is ShadowKind.BACKLASH:
            return self.half_range is not None
        return self.stiffness is not None and self.damping is not None

    @property
    def needs_inertia(self) -> bool:
        return self.kind is not ShadowKind.BACKLASH

    @property
    def equality_name(self) -> str:
        return f"{self.name}_eq"

    def with_inertia(self, i_eff: float) -> ShadowJointSpec:
        """Resolve the parameters that depend on the compiled effective inertia."""
        if not self.needs_inertia:
            return self
        if not np.isfinite(i_eff) or i_eff <= 0.0:
            raise ValueError(
                f"{self.name}: effective inertia about the joint axis came out as "
                f"{i_eff}, which cannot carry a compliance mode. The two-pass "
                "compile in inject read it from mj_fullM; a non-positive value "
                "means the fragment landed on a body with no downstream mass."
            )
        if self.kind is ShadowKind.SERIES_ELASTIC:
            k = self.stiffness
            if k is None:
                raise ValueError(
                    f"{self.name}: series-elastic stiffness is the dose, it must be set"
                )
        else:
            if self.stiffness_per_inertia is None:
                raise ValueError(
                    f"{self.name}: D7's stiffness is fixed by a mode frequency times "
                    "the compiled inertia, and no frequency was bound"
                )
            k = self.stiffness_per_inertia * i_eff
        d = 2.0 * COMPLIANCE_DAMPING_RATIO * float(np.sqrt(k * i_eff))
        return replace(self, stiffness=float(k), damping=float(d))


def _fmt(x: float) -> str:
    return f"{float(x):.17g}"


def _fmt_vec(v: tuple[float, ...]) -> str:
    return " ".join(_fmt(x) for x in v)


def assert_driven_armature(armature: float, joint_name: str) -> None:
    """9.2.4 trap 3: the driven joint has to carry the rotor inertia."""
    if armature <= 0.0:
        raise ValueError(
            f"{joint_name} has armature {armature}; a co-located shadow joint on a "
            "driven joint with no added inertia makes the joint-space mass matrix "
            "singular (9.2.4 trap 3). Set a positive armature on this joint in the "
            "family MJCF and set the identical value on the clean twin -- a "
            "mismatch between the two sides breaks the FGW argument outright."
        )


def _orthogonal_axis(axis: tuple[float, float, float]) -> tuple[float, float, float]:
    """A deterministic unit vector orthogonal to `axis`, for D7's bending mode."""
    a = np.asarray(axis, dtype=np.float64)
    norm = np.linalg.norm(a)
    if norm == 0.0:
        raise ValueError("a joint axis of zero length has no orthogonal complement")
    a = a / norm
    basis = np.eye(3)[int(np.argmin(np.abs(a)))]
    b = basis - np.dot(basis, a) * a
    b = b / np.linalg.norm(b)
    return (float(b[0]), float(b[1]), float(b[2]))


def shadow_joint_names(delta: Delta, arm_joint_names: tuple[str, ...]) -> tuple[str, ...]:
    """Names the fragment will introduce, in model order."""
    suffix = SHADOW_SUFFIX.get(delta.defect_code)
    if suffix is None:
        return ()
    return tuple(
        f"{name}{suffix}"
        for name, scale in zip(arm_joint_names, delta.joint_scale, strict=True)
        if scale != 0.0
    )


def plan_for(
    delta: Delta,
    *,
    arm_joint_names: tuple[str, ...],
    joint_axes: dict[str, tuple[float, float, float]],
    joint_positions: dict[str, tuple[float, float, float]],
    joint_armature: dict[str, float],
) -> tuple[ShadowJointSpec, ...]:
    """The fragment this delta needs, empty for the ten defects that do not change the graph.

    Called once with the defective delta and once with `delta.zero()`; the two
    plans differ only in the numbers, never in the node set, which is what makes
    the relaxed 9.3.4 assertion hold.
    """
    suffix = SHADOW_SUFFIX.get(delta.defect_code)
    if suffix is None:
        return ()

    specs: list[ShadowJointSpec] = []
    for name, scale in zip(arm_joint_names, delta.joint_scale, strict=True):
        if scale == 0.0:
            continue
        assert_driven_armature(joint_armature[name], name)
        axis = joint_axes[name]
        pos = joint_positions[name]
        if delta.defect_code == "D4hi":
            band = float(delta.joint_values("backlash")[arm_joint_names.index(name)])
            specs.append(
                ShadowJointSpec(
                    name=f"{name}{suffix}",
                    parent_joint=name,
                    kind=ShadowKind.BACKLASH,
                    axis=axis,
                    pos=pos,
                    half_range=0.5 * band,
                    stiffness=None,
                    damping=None,
                )
            )
        elif delta.defect_code == "D3a":
            k = float(delta.joint_values("k_transmission")[arm_joint_names.index(name)])
            specs.append(
                ShadowJointSpec(
                    name=f"{name}{suffix}",
                    parent_joint=name,
                    kind=ShadowKind.SERIES_ELASTIC,
                    axis=axis,
                    pos=pos,
                    half_range=None,
                    stiffness=k,
                    damping=None,
                )
            )
        else:
            ratio = float(delta.joint_values("link_compliance")[arm_joint_names.index(name)])
            if ratio <= 0.0:
                raise ValueError(
                    f"D7 link_compliance must be positive, got {ratio}; the rigid "
                    "limit is the small identity value, not zero"
                )
            specs.append(
                ShadowJointSpec(
                    name=f"{name}{suffix}",
                    parent_joint=name,
                    kind=ShadowKind.LINK_FLEX,
                    axis=_orthogonal_axis(axis),
                    pos=pos,
                    half_range=None,
                    stiffness=None,
                    damping=None,
                    stiffness_per_inertia=LINK_FLEX_REFERENCE_OMEGA**2 / ratio,
                )
            )
    return tuple(specs)


def resolve_inertia(
    plan: tuple[ShadowJointSpec, ...], inertia: dict[str, float]
) -> tuple[ShadowJointSpec, ...]:
    """Second pass: bind the inertia-dependent parameters to the compiled model."""
    return tuple(
        spec.with_inertia(inertia[spec.name]) if spec.needs_inertia else spec
        for spec in plan
    )


def _joint_attrs(spec: ShadowJointSpec) -> dict[str, str]:
    attrs = {
        "name": spec.name,
        "type": "hinge",
        "pos": _fmt_vec(spec.pos),
        "axis": _fmt_vec(spec.axis),
        "armature": _fmt(spec.armature),
        # 9.2.4's `class="backlash"` default block, spelled out per joint so that
        # the fragment does not depend on a <default> section existing.
        "damping": _fmt(spec.damping if spec.damping is not None else 0.0),
        "frictionloss": "0",
    }
    if spec.kind is ShadowKind.BACKLASH:
        attrs["limited"] = "true"
        attrs["range"] = f"{_fmt(-spec.half_range)} {_fmt(spec.half_range)}"
    else:
        attrs["limited"] = "false"
        attrs["stiffness"] = _fmt(spec.stiffness)
    return attrs


def rewrite_xml(xml: str, plan: tuple[ShadowJointSpec, ...]) -> str:
    """Insert the fragment into a compiled-ready MJCF string.

    Registered as a robosuite xml processor, so it re-runs on every
    `hard_reset` -- which is the only reason the extra node survives a reset at
    all (9.2.0 discipline 1).
    """
    if not plan:
        return xml

    root = ET.fromstring(xml)
    parents = {child: parent for parent in root.iter() for child in parent}
    by_name = {
        joint.get("name"): joint
        for joint in root.iter("joint")
        if joint.get("name") is not None
    }

    equality = root.find("equality")
    if equality is None:
        equality = ET.SubElement(root, "equality")

    for spec in plan:
        if not spec.is_resolved:
            raise ValueError(
                f"{spec.name} still carries an unresolved inertia-dependent "
                "parameter; call resolve_inertia against a compiled model first"
            )
        driven = by_name.get(spec.parent_joint)
        if driven is None:
            raise KeyError(
                f"{spec.parent_joint!r} is not a joint in this MJCF; the fragment "
                f"resolves joints by name because a shadow joint shifts every "
                f"index behind it (9.2.6 trap iii). Present: {sorted(by_name)}"
            )
        body = parents[driven]
        node = ET.Element("joint", _joint_attrs(spec))
        body.insert(list(body).index(driven) + 1, node)

        if spec.kind is ShadowKind.BACKLASH:
            # Omitting joint2 degenerates the polynomial constraint to y = y0 + a0,
            # i.e. pins the shadow joint at its qpos0 (9.2.4). solimp's width entry
            # is the low-impedance dead zone and carries the half band.
            solimp = (*BACKLASH_SOLIMP_HEAD, spec.half_range, *BACKLASH_SOLIMP_TAIL)
            ET.SubElement(
                equality,
                "joint",
                {
                    "name": spec.equality_name,
                    "joint1": spec.name,
                    "solref": _fmt_vec(BACKLASH_SOLREF),
                    "solimp": _fmt_vec(solimp),
                },
            )

    return ET.tostring(root, encoding="unicode")
