    "COMPLIANCE_DAMPING_RATIO",
    "LINK_FLEX_REFERENCE_OMEGA",
    "BACKLASH_SOLREF",
    "BACKLASH_SOLIMP_HEAD",
    "BACKLASH_SOLIMP_TAIL",
